#!/usr/bin/env python3
"""
Muon Shaders - tools/gen_wrappers.py

Generates the thin per-program entry points in shaders/ from a single manifest.

Iris resolves a program by looking for shaders/<name>.vsh and shaders/<name>.fsh.
Keeping twenty near-identical five-line files in sync by hand is a source of
silent breakage (a missing program silently falls back to vanilla rendering), so
they are generated here instead and checked in.

Run from the repository root:

    python tools/gen_wrappers.py            # write the files
    python tools/gen_wrappers.py --check    # fail if anything is out of date
"""

