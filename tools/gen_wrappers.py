def render(name: str, ext: str, impl: str, defines: list[str]) -> str:
    lines = [HEADER.format(name=name, ext=ext, impl=f"program/{impl}")]
    lines.append(VERSION)
    lines.append("")
    for define in defines:
        lines.append(f"#define {define}")
    if defines:
        lines.append("")
    lines.append(f'#include "/program/{impl}"')
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    stale: list[str] = []
    for name, (vsh_impl, fsh_impl, defines) in PROGRAMS.items():
        for ext, impl in (("vsh", vsh_impl), ("fsh", fsh_impl)):
            path = SHADERS / f"{name}.{ext}"
            content = render(name, ext, impl, defines)
            if args.check:
                if not path.exists() or path.read_text(encoding="utf-8") != content:
                    stale.append(str(path.relative_to(ROOT)))
            else:
                path.write_text(content, encoding="utf-8")

    if args.check:
        if stale:
            print("Out of date wrapper files:")
            for item in stale:
                print(f"  {item}")
            return 1
        print(f"{len(PROGRAMS) * 2} wrapper files are up to date")
        return 0

    print(f"wrote {len(PROGRAMS) * 2} wrapper files into shaders/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
